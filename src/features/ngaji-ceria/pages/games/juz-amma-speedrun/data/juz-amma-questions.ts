const TYPES: QuestionType[] = ["lanjut-ayat", "nama-surah", "arti-ayat"];
const answerFor = (verse: VerseSeed, type: QuestionType) =>
  type === "lanjut-ayat"
    ? verse.nextArabic
    : type === "nama-surah"
      ? verse.surahName
      : verse.translation;

// Beberapa ayat memiliki teks Arab yang sama (mis. Al-Kafirun 3 & 5, atau ayat yang muncul di dua surah).
// Soal tidak dibuat bila jawabannya jadi ambigu.
const sameArabic = new Map<string, VerseSeed[]>();
JUZ_AMMA_VERSES.forEach((verse) =>
  sameArabic.set(verse.arabic, [
    ...(sameArabic.get(verse.arabic) ?? []),
    verse,
  ]),
);
const isAskable = (verse: VerseSeed, type: QuestionType): boolean => {
  const twins = sameArabic.get(verse.arabic) ?? [verse];
  if (type === "lanjut-ayat")
    return verse.nextArabic !== "" && twins.length === 1;
  return twins.every(
    (twin) => answerFor(twin, type) === answerFor(verse, type),
  );
};

// 564 ayat × 3 tipe (dikurangi ayat terakhir surah untuk "lanjut-ayat" dan ayat kembar), masing-masing dengan empat opsi unik.
export const JUZ_AMMA_QUESTIONS: Question[] = JUZ_AMMA_VERSES.flatMap(
  (verse, verseIndex) =>
    TYPES.filter((type) => isAskable(verse, type)).map((type) => {
      const correct = answerFor(verse, type);
      const candidates = JUZ_AMMA_VERSES.slice(verseIndex + 1).concat(
        JUZ_AMMA_VERSES.slice(0, verseIndex),
      );
      const distractors = [
        ...new Set(candidates.map((item) => answerFor(item, type))),
      ]
        .filter((answer) => answer !== "" && answer !== correct)
        .slice(0, 3);
      return {
        id: `${verse.id}:${type}`,
        type,
        prompt:
          type === "lanjut-ayat"
            ? "Ayat berikutnya adalah…"
            : type === "nama-surah"
              ? "Potongan ini dari surah apa?"
              : "Apa arti ayat ini?",
        promptArabic: verse.arabic,
        options: [correct, ...distractors],
        correctIndex: 0,
        surahName: verse.surahName,
        ayahNumber: verse.ayahNumber,
      };
    }),
);

export function shuffleQuestions(): Question[] {
  // Distribusi tetap 40% lanjutan, 30% nama, 30% arti; opsi turut diacak.
  const session = TYPES.flatMap((type) =>
    shuffle(JUZ_AMMA_QUESTIONS.filter((q) => q.type === type)).slice(
      0,
      type === "lanjut-ayat" ? 4 : 3,
    ),
  );
  return shuffle(session).map((question) => {
    const answer = question.options[question.correctIndex];
    const options = shuffle(question.options);
    return { ...question, options, correctIndex: options.indexOf(answer) };
  });
}
